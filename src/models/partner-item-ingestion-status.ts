import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { ingestionErrorsSchema, type IngestionErrors } from "./ingestion-errors.js";
import { ingestionStatusSchema, type IngestionStatus } from "./ingestion-status.js";

/** The ingestion status of an individual item. */
export type PartnerItemIngestionStatus = {
  /** Mart ID that a user or seller uses for a marketplace. */
  martId?: number;
  /** An arbitrary alphanumeric unique ID, seller-specified, identifying each item. */
  sku?: string;
  /** An alphanumeric product ID, generated by Walmart. */
  wpid?: string;
  /** index of items in the feed. */
  index?: number;
  /** Can be one of the following: DATA_ERROR, SYSTEM_ERROR, TIMEOUT_ERROR, or INPROGRESS */
  ingestionStatus: IngestionStatus;
  /** List of errors for an item. */
  ingestionErrors?: IngestionErrors;
};

export const partnerItemIngestionStatusSchema: Schema<PartnerItemIngestionStatus> =
  s.object<PartnerItemIngestionStatus>({
    martId: s.optional(s.int()),
    sku: s.optional(s.string()),
    wpid: s.optional(s.string()),
    index: s.optional(s.int()),
    ingestionStatus: ingestionStatusSchema,
    ingestionErrors: s.optional(s.lazy(() => ingestionErrorsSchema)),
  });
