import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

/**
 * RFC 9457 problem details for HTTP APIs (https://www.rfc-editor.org/rfc/rfc9457). Used for all 4xx
 * and 5xx error responses in the Rich media management API.
 */
export type ProblemDetailsError1 = {
  /**
   * A URI reference that identifies the problem type. Dereferencing this URI should provide
   * human-readable documentation.
   */
  type?: string;
  /**
   * A short, human-readable summary of the problem type. Should not change from occurrence to
   * occurrence.
   */
  title?: string;
  /** The HTTP status code generated by the origin server for this occurrence of the problem. */
  status?: number;
  /** A human-readable explanation specific to this occurrence of the problem. */
  detail?: string;
  /** A URI reference that identifies the specific occurrence of the problem. May be relative. */
  instance?: string;
  /**
   * Walmart rich media-specific error code. Pattern: RM-XXXX (e.g. RM-4001 for missing param,
   * RM-4002 for invalid value).
   */
  code?: string;
};

export const problemDetailsError1Schema: Schema<ProblemDetailsError1> = s.object<ProblemDetailsError1>({
  type: s.optional(s.string()),
  title: s.optional(s.string()),
  status: s.optional(s.int()),
  detail: s.optional(s.string()),
  instance: s.optional(s.string()),
  code: s.optional(s.string()),
});
