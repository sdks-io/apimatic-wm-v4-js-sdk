import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { gmvAmountSchema, type GmvAmount } from "./gmv-amount.js";
import { price2Schema, type Price2 } from "./price2.js";

export type GetUnpublishedItemsPayload = {
  /** The GTIN-compatible Product ID (i.e. UPC or EAN) */
  gtin?: string;
  marketPrice?: Price2;
  /** The Date when item becomes available to sell in Walmart */
  offerStartDate?: string;
  /** If item is trending in walmart */
  marketTrending?: string;
  /**
   * The lifecycle status of an item describes where the item listing is in the overall lifecycle
   */
  lifecycleStatus?: string;
  /** It outlines the reason for an item when unpublished */
  unpublishReasons?: string;
  /** Percentage of number of items that are converted into sales */
  conversionRate?: number;
  /** A seller-specified, alphanumeric string uniquely identifying the product name */
  productName?: string;
  gmvAmount?: GmvAmount;
  /** Specifies the item identifier generated by Walmart */
  itemId?: string;
  /** An average rating number for the item from customers */
  customerRating?: string;
  /** number of times this item is viewed by customers */
  pageViews?: number;
  price?: Price2;
  /** The Date item becomes to Unpublished */
  unpublishedDate?: string;
  /** Specifies the item brand */
  brand?: string;
  /** String of letters and/or numbers a partner uses to identify the item */
  sku?: string;
  /** Information about the condition of the product */
  condition?: string;
  /** A seller-specified, alphanumeric string uniquely identifying the Product Type */
  productType?: string;
  /** The Date when item becomes unavailable to sell in Walmart */
  offerEndDate?: string;
  /** The status of an item when the item is in the submission process */
  publishStatus?: string;
  /** Indicates whether the item is identified as a customer favorite based on customer demand. */
  isCustomerFavorite?: boolean;
};

export const getUnpublishedItemsPayloadSchema: Schema<GetUnpublishedItemsPayload> =
  s.object<GetUnpublishedItemsPayload>({
    gtin: s.optional(s.string()),
    marketPrice: s.optional(s.lazy(() => price2Schema)),
    offerStartDate: s.optional(s.string()),
    marketTrending: s.optional(s.string()),
    lifecycleStatus: s.optional(s.string()),
    unpublishReasons: s.optional(s.string()),
    conversionRate: s.optional(s.int()),
    productName: s.optional(s.string()),
    gmvAmount: s.optional(s.lazy(() => gmvAmountSchema)),
    itemId: s.optional(s.string()),
    customerRating: s.optional(s.string()),
    pageViews: s.optional(s.int()),
    price: s.optional(s.lazy(() => price2Schema)),
    unpublishedDate: s.optional(s.string()),
    brand: s.optional(s.string()),
    sku: s.optional(s.string()),
    condition: s.optional(s.string()),
    productType: s.optional(s.string()),
    offerEndDate: s.optional(s.string()),
    publishStatus: s.optional(s.string()),
    isCustomerFavorite: s.optional(s.boolean()),
  });
